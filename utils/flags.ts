export const getCountryNameAr = (nationalityAr: string | undefined): string | undefined => {
    if (!nationalityAr) return undefined;
    const normalized = nationalityAr.trim();
    if (arabicNationalityToCountryName[normalized]) {
        return arabicNationalityToCountryName[normalized];
    }
    for (const [key, value] of Object.entries(arabicNationalityToCountryName)) {
        if (normalized.includes(key) || key.includes(normalized)) {
            return value;
        }
    }
    return undefined;
};

export const getCountryCode = (nationalityAr: string): string | undefined => {
    if (!nationalityAr) return undefined;
    
    // Normalize string: remove spaces, handle common variations
    const normalized = nationalityAr.trim();
    
    // Direct match
    if (arabicNationalityToCountryCode[normalized]) {
        return arabicNationalityToCountryCode[normalized];
    }
    
    // Partial match or common variants
    for (const [key, value] of Object.entries(arabicNationalityToCountryCode)) {
        if (normalized.includes(key) || key.includes(normalized)) {
            return value;
        }
    }
    
    return undefined;
};
